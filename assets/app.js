    var band = missing ? 'none'
      : scaleKind === 'pct'
        ? (val >= 70 ? 'high' : val >= 40 ? 'mid' : 'low')
        : (val >= 25 ? 'high' : val >= 15 ? 'mid' : 'low');
    var COL = { high: 'var(--danger)', mid: 'var(--warn)', low: 'var(--down)', none: 'var(--idle)' };
    var PILL = { high: 'up', mid: 'warn', low: 'down', none: 'grey' };
